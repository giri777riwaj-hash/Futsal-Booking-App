"""
Futsal Booking App — REST API backend (Flask) — v2

New in this version:
  - Player accounts (optional password) alongside guest checkout
  - Loyalty: every 10 paid bookings earns 1 free game, auto-applied on request
  - Split-payment: a booking's cost can be divided among friends, each share
    can be marked settled, and a shareable WhatsApp text is generated by the
    frontend from data this API returns
  - Admin endpoints are unchanged and still password-gated. The frontend
    never links to the admin page from anywhere a customer can reach —
    that's the "secret page" ask — but this API is the actual gate, so
    nothing here is accessible without ADMIN_PASSWORD regardless of how
    someone reaches it.

Run with:  python app.py
Serves on: http://localhost:5000
"""

import os
import sqlite3
from werkzeug.security import generate_password_hash, check_password_hash

from flask import Flask, jsonify, request
from flask_cors import CORS

DB_PATH = os.path.join(os.path.dirname(__file__), "futsal.db")
SCHEMA_PATH = os.path.join(os.path.dirname(__file__), "schema.sql")
ADMIN_PASSWORD = "admin123"  # class-project placeholder, not real security

LOYALTY_TARGET = 10  # paid bookings needed to earn 1 free game

DAY_TEMPLATE = [
    ("06:00", "07:00"), ("07:00", "08:00"),
    ("17:00", "18:00"), ("18:00", "19:00"),
    ("19:00", "20:00"), ("20:00", "21:00"),
]

app = Flask(__name__)
CORS(app)


# ---------------------------------------------------------------------
# Database helpers
# ---------------------------------------------------------------------

def get_conn():
    conn = sqlite3.connect(DB_PATH)
    conn.execute("PRAGMA foreign_keys = ON")
    conn.row_factory = sqlite3.Row
    return conn


def ensure_db():
    if not os.path.exists(DB_PATH):
        with open(SCHEMA_PATH, "r") as f:
            script = f.read()
        conn = sqlite3.connect(DB_PATH)
        conn.executescript(script)
        conn.commit()
        conn.close()


def get_ground(conn):
    return conn.execute("SELECT * FROM grounds LIMIT 1").fetchone()


def get_slots_for_date(conn, ground_id, slot_date):
    return conn.execute(
        """SELECT * FROM time_slots
           WHERE ground_id = ? AND slot_date = ?
           ORDER BY start_time""",
        (ground_id, slot_date),
    ).fetchall()


def set_slot_status(conn, slot_id, new_status):
    conn.execute("UPDATE time_slots SET status = ? WHERE slot_id = ?", (new_status, slot_id))
    conn.commit()


def add_slot(conn, ground_id, slot_date, start_time, end_time):
    conn.execute(
        """INSERT INTO time_slots (ground_id, slot_date, start_time, end_time)
           VALUES (?, ?, ?, ?)""",
        (ground_id, slot_date, start_time, end_time),
    )
    conn.commit()


def generate_standard_day(conn, ground_id, slot_date):
    added = 0
    for start, end in DAY_TEMPLATE:
        try:
            add_slot(conn, ground_id, slot_date, start, end)
            added += 1
        except sqlite3.IntegrityError:
            pass
    return added


def public_user(row):
    """Strip password_hash before this ever reaches the frontend."""
    if row is None:
        return None
    d = dict(row)
    d.pop("password_hash", None)
    return d


def row_to_dict(row):
    return dict(row) if row is not None else None


def rows_to_list(rows):
    return [dict(r) for r in rows]


