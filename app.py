@app.route("/api/bookings", methods=["POST"])
def api_create_booking():
    """
    Body:
      player_id: required (from signup/login/guest)
      slot_id, method: required unless use_free_game is true
      use_free_game: optional bool — redeem a banked free game instead of paying
      splits: optional list of {friend_name, friend_phone, share_amount}
    """
    data = request.get_json()
    player_id = data.get("player_id")
    slot_id = data.get("slot_id")
    use_free_game = bool(data.get("use_free_game"))
    method = data.get("method", "cash")
    splits = data.get("splits") or []

    if not player_id or not slot_id:
        return jsonify({"error": "player_id and slot_id are required"}), 400

    conn = get_conn()
    ground = get_ground(conn)
    price = ground["price_per_hour"]

    user = conn.execute("SELECT * FROM users WHERE user_id = ?", (player_id,)).fetchone()
    if not user:
        conn.close()
        return jsonify({"error": "Unknown player"}), 404

    if use_free_game and user["free_games_available"] < 1:
        conn.close()
        return jsonify({"error": "No free games available to redeem"}), 400

    is_free = 1 if use_free_game else 0
    amount = 0 if use_free_game else price
    pay_method = "free_reward" if use_free_game else method

    try:
        cur = conn.execute(
            "INSERT INTO bookings (player_id, slot_id, is_free) VALUES (?, ?, ?)",
            (player_id, slot_id, is_free),
        )
        booking_id = cur.lastrowid
        conn.execute(
            "INSERT INTO payments (booking_id, amount, method) VALUES (?, ?, ?)",
            (booking_id, amount, pay_method),
        )

        loyalty_count = user["loyalty_count"]
        free_games_available = user["free_games_available"]
        reward_just_earned = False

        if use_free_game:
            free_games_available -= 1
        else:
            loyalty_count += 1
            if loyalty_count >= LOYALTY_TARGET:
                loyalty_count = 0
                free_games_available += 1
                reward_just_earned = True

        conn.execute(
            "UPDATE users SET loyalty_count = ?, free_games_available = ? WHERE user_id = ?",
            (loyalty_count, free_games_available, player_id),
        )

        if reward_just_earned:
            conn.execute(
                "INSERT INTO notifications (user_id, message, type) VALUES (?, ?, 'loyalty')",
                (player_id, "You just earned a free game! It's ready to use on your next booking."),
            )

        # optional split: divide this booking's amount among friends
        for s in splits:
            fname = (s.get("friend_name") or "").strip()
            if not fname:
                continue
            conn.execute(
                """INSERT INTO booking_splits (booking_id, friend_name, friend_phone, share_amount)
                   VALUES (?, ?, ?, ?)""",
                (booking_id, fname, s.get("friend_phone"), s.get("share_amount", 0)),
            )

        conn.commit()
    except sqlite3.IntegrityError:
        conn.rollback()
        conn.close()
        return jsonify({"error": "Sorry, that slot was just taken. Please pick another."}), 409

    refreshed = conn.execute("SELECT * FROM users WHERE user_id = ?", (player_id,)).fetchone()
    conn.close()
    return jsonify({
        "ok": True,
        "booking_id": booking_id,
        "amount": amount,
        "reward_just_earned": reward_just_earned,
        "user": public_user(refreshed),
    })


@app.route("/api/bookings/player/<int:player_id>", methods=["GET"])
def api_player_bookings(player_id):
    conn = get_conn()
    rows = conn.execute(
        """SELECT b.booking_id, t.slot_date, t.start_time, t.end_time,
                  b.status, b.is_free, p.amount, p.method, p.status AS payment_status
           FROM bookings b
           JOIN time_slots t ON t.slot_id = b.slot_id
           LEFT JOIN payments p ON p.booking_id = b.booking_id
           WHERE b.player_id = ?
           ORDER BY t.slot_date DESC, t.start_time DESC""",
        (player_id,),
    ).fetchall()
    conn.close()
    return jsonify(rows_to_list(rows))


