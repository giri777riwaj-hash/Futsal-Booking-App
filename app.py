@app.route("/api/slots/generate-day", methods=["POST"])
def api_generate_day():
    data = request.get_json()
    if data.get("admin_password") != ADMIN_PASSWORD:
        return jsonify({"error": "Invalid admin password"}), 403
    conn = get_conn()
    added = generate_standard_day(conn, data["ground_id"], data["date"])
    conn.close()
    return jsonify({"added": added})


@app.route("/api/slots/custom", methods=["POST"])
def api_add_custom_slot():
    data = request.get_json()
    if data.get("admin_password") != ADMIN_PASSWORD:
        return jsonify({"error": "Invalid admin password"}), 403
    conn = get_conn()
    try:
        add_slot(conn, data["ground_id"], data["date"], data["start_time"], data["end_time"])
        conn.close()
        return jsonify({"ok": True})
    except sqlite3.IntegrityError as e:
        conn.close()
        return jsonify({"error": str(e)}), 400


@app.route("/api/slots/<int:slot_id>/status", methods=["PATCH"])
def api_set_slot_status(slot_id):
    data = request.get_json()
    if data.get("admin_password") != ADMIN_PASSWORD:
        return jsonify({"error": "Invalid admin password"}), 403
    new_status = data.get("status")
    if new_status not in ("available", "blocked"):
        return jsonify({"error": "status must be available or blocked"}), 400
    conn = get_conn()
    row = conn.execute("SELECT status FROM time_slots WHERE slot_id = ?", (slot_id,)).fetchone()
    if row is None:
        conn.close()
        return jsonify({"error": "Slot not found"}), 404
    if row["status"] == "booked":
        conn.close()
        return jsonify({"error": "Cannot toggle a booked slot — cancel the booking first"}), 400
    set_slot_status(conn, slot_id, new_status)
    conn.close()
    return jsonify({"ok": True})


