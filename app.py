@app.route("/api/auth/signup", methods=["POST"])
def api_signup():
    data = request.get_json()
    name = (data.get("name") or "").strip()
    email = (data.get("email") or "").strip().lower()
    phone = (data.get("phone") or "").strip()
    password = data.get("password") or ""

    if not (name and email and phone and password):
        return jsonify({"error": "Name, email, phone and password are all required."}), 400
    if len(password) < 6:
        return jsonify({"error": "Password must be at least 6 characters."}), 400

    conn = get_conn()
    existing = conn.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()

    if existing:
        if existing["password_hash"]:
            conn.close()
            return jsonify({"error": "An account with this email already exists. Try logging in instead."}), 409
        # this email has booked as a guest before — turn it into a real account,
        # keeping their existing loyalty count and booking history intact
        conn.execute(
            "UPDATE users SET password_hash = ?, name = ?, phone = ? WHERE user_id = ?",
            (generate_password_hash(password), name, phone, existing["user_id"]),
        )
        conn.commit()
        user = conn.execute("SELECT * FROM users WHERE user_id = ?", (existing["user_id"],)).fetchone()
        conn.close()
        return jsonify({"ok": True, "user": public_user(user)})

    cur = conn.execute(
        "INSERT INTO users (name, email, phone, role, password_hash) VALUES (?, ?, ?, 'player', ?)",
        (name, email, phone, generate_password_hash(password)),
    )
    conn.commit()
    user = conn.execute("SELECT * FROM users WHERE user_id = ?", (cur.lastrowid,)).fetchone()
    conn.close()
    return jsonify({"ok": True, "user": public_user(user)})


@app.route("/api/auth/login", methods=["POST"])
def api_login():
    data = request.get_json()
    email = (data.get("email") or "").strip().lower()
    password = data.get("password") or ""

    conn = get_conn()
    user = conn.execute("SELECT * FROM users WHERE email = ? AND role = 'player'", (email,)).fetchone()
    conn.close()

    if not user or not user["password_hash"] or not check_password_hash(user["password_hash"], password):
        return jsonify({"error": "Incorrect email or password."}), 401

    return jsonify({"ok": True, "user": public_user(user)})


@app.route("/api/auth/guest", methods=["POST"])
def api_guest():
    """Book without an account. Reuses an existing guest/account row by email
    if one exists (so loyalty carries over), otherwise creates a bare guest row."""
    data = request.get_json()
    name = (data.get("name") or "").strip()
    email = (data.get("email") or "").strip().lower()
    phone = (data.get("phone") or "").strip()

    if not (name and email and phone):
        return jsonify({"error": "Name, email and phone are required."}), 400

    conn = get_conn()
    row = conn.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()
    if row:
        conn.close()
        return jsonify({"ok": True, "user": public_user(row)})

    cur = conn.execute(
        "INSERT INTO users (name, email, phone, role) VALUES (?, ?, ?, 'player')",
        (name, email, phone),
    )
    conn.commit()
    user = conn.execute("SELECT * FROM users WHERE user_id = ?", (cur.lastrowid,)).fetchone()
    conn.close()
    return jsonify({"ok": True, "user": public_user(user)})


@app.route("/api/users/<int:user_id>", methods=["GET"])
def api_get_user(user_id):
    conn = get_conn()
    user = conn.execute("SELECT * FROM users WHERE user_id = ?", (user_id,)).fetchone()
    conn.close()
    if not user:
        return jsonify({"error": "Not found"}), 404
    return jsonify(public_user(user))


